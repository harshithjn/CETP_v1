def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="dist")
    args = ap.parse_args()
    out = PROJECT_DIR / args.out
    out.mkdir(exist_ok=True)

    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=PROJECT_DIR,
                                capture_output=True, text=True).stdout.strip() or None
        dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=PROJECT_DIR,
                                    capture_output=True, text=True).stdout.strip())
    except OSError:
        commit, dirty = None, None

    files, missing = [], []
    for rel, desc in INCLUDE:
        p = PROJECT_DIR / rel
        if not p.exists():
            missing.append(rel)
            continue
        if p.is_dir():
            for f in sorted(p.rglob("*")):
                if f.is_file() and not f.name.startswith("."):
                    files.append({"path": str(f.relative_to(PROJECT_DIR)),
                                  "description": desc, "bytes": f.stat().st_size,
                                  "sha256": sha256(f)})
        else:
            files.append({"path": rel, "description": desc, "bytes": p.stat().st_size,
                          "sha256": sha256(p)})

    for e in EXTERNAL:
        lp = PROJECT_DIR / e["local_path"]
        if lp.is_file():
            e["sha256_of_local_copy"] = sha256(lp)
            e["bytes"] = lp.stat().st_size

    manifest = {
        "name": "CETP cross-environment query runtime datasets",
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "git_commit": commit,
        "git_dirty": dirty,
        "licence": {"data": "CC BY 4.0 (proposed)", "code": "MIT (proposed)",
                    "caveat": "TPC-H/TPC-DS are TPC specifications; see tpcds-kit EULA.txt "
                              "before redistributing generated SQL."},
        "datasheet": "DATASHEET.md",
        "canonical_numbers": "results/CANONICAL.md",
        "known_defects": "See DATASHEET.md, section Composition. Notably: repetition 0/1 of "
                         "each cell is a cold-cache outlier that contaminates p95/p99; the "
                         "STREAM bandwidth probe is lost; q16/q20 are approximate "
                         "reconstructions; no raw EXPLAIN plans were retained from the EC2 "
                         "collection.",
        "n_files": len(files),
        "total_bytes": sum(f["bytes"] for f in files),
        "files": files,
        "external_dependencies_not_redistributed": EXTERNAL,
    }
    if missing:
        manifest["missing_at_package_time"] = missing

    mpath = out / "MANIFEST.json"
    mpath.write_text(json.dumps(manifest, indent=2) + "\n")

    tar_path = out / "cetp-datasets.tar.gz"
    with tarfile.open(tar_path, "w:gz") as tf:
        for f in files:
            tf.add(PROJECT_DIR / f["path"], arcname=f"cetp-datasets/{f['path']}")
        tf.add(mpath, arcname="cetp-datasets/MANIFEST.json")

    print(f"packaged {len(files)} files, {manifest['total_bytes'] / 1e6:.1f} MB uncompressed")
    print(f"  {tar_path}  ({tar_path.stat().st_size / 1e6:.1f} MB)")
    print(f"  {mpath}")
    if missing:
        print(f"  MISSING ({len(missing)}): {', '.join(missing)}")
    if dirty:
        print("  WARNING: working tree is dirty; the git_commit in the manifest does not "
              "fully describe this archive.")
    print("\nNOT included (third-party): " + ", ".join(e["name"] for e in EXTERNAL))
    print("Publishing to Zenodo/HuggingFace is left to the author -- it needs their account.")


if __name__ == "__main__":
    main()
